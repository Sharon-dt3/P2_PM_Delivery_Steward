"""The README's headline numbers, rendered FROM the committed results file so they can never be typed wrong or left behind (PM-33).

`eval/results.jsonl` holds one record per run: when it ran, the code revision, the model id, every prompt's version, and every metric with its measured value,
target and result. This module reads the newest default record (the scripted gateway: all nine golden cases, deterministic) and the newest live-model record, if there is
one, and renders the table that sits between the markers in README.md. `scripts/eval_readme.py --write` puts it there; `--check` (and a test) fails when the README
no longer matches the file.

Which numbers are "headline" is fixed here, by case, and every metric of a case still counts toward its pass/fail.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

BEGIN = "<!-- eval:begin -- generated by scripts/eval_readme.py from eval/results.jsonl; do not edit by hand -->"
END = "<!-- eval:end -->"
SCRIPTED_MODEL = "scripted-gateway"
CASES = ("GC1", "GC2", "GC3", "GC4", "GC5", "GC6", "GC7", "GC8", "GC9")

# case -> (name, what is measured, [(label, metric id)] for the headline cell)
HEADLINES: dict[str, tuple[str, str, list[tuple[str, str]]]] = {
    "GC1": ("Citation rate", "factual brief lines whose reference resolves to a real item", [("citation rate", "GC1-citation-rate")]),
    "GC2": ("Fabrication probe", "lines claiming a transition, commit or message that is not in the snapshot (the headline number)", [("fabricated claims", "GC2-fabricated-claim-count")]),
    "GC3": ("Delta correctness", "the computed changed set against the hand labels, the twice-moved item reported once",
            [("precision", "GC3-delta-precision"), ("recall", "GC3-delta-recall")]),
    "GC4": ("Gap detection", "blockers missing from the risk log found; none proposed twice after a rejection",
            [("precision", "GC4-gap-precision"), ("recall", "GC4-gap-recall"), ("duplicates", "GC4-duplicate-count")]),
    "GC5": ("Promotion threshold", "the proposed set at a 2-day and a 4-day threshold, and that it shrinks correctly",
            [("2-day errors", "GC5-two-day-set-errors"), ("4-day errors", "GC5-four-day-set-errors"), ("shrink errors", "GC5-shrink-errors")]),
    "GC6": ("Approval enforcement", "direct writes on pending or rejected proposals (a post, the risk log, the tracker, a saved weekly report); audit completeness",
            [("message bypasses", "GC6-write-bypass-count"), ("risk-log bypasses", "GC6-risk-write-bypass-count"), ("tracker bypasses", "GC6-tracker-write-bypass-count"),
             ("report bypasses", "GC6-report-write-bypass-count")]),
    "GC7": ("Shared nudge cap and order", "nudges per person per day counting P1's, and a nudge before any escalation",
            [("cap breaches", "GC7-cap-breach-count"), ("order violations", "GC7-escalation-order-violation-count")]),
    "GC8": ("Scope and consent refusal", "proposals from an outcome record lacking P1's flag; logged refusals",
            [("leaked proposals", "GC8-leaked-proposal-count"), ("records refused", "GC8-refused-record-count")]),
    "GC9": ("Determinism of facts", "facts that differ across two generations of the brief from one snapshot", [("divergent facts", "GC9-fact-divergence-count")]),
}
_SYMBOL = {"at_least": "≥", "at_most": "≤"}


def load_records(path: str | Path) -> list[dict]:
    return [json.loads(line) for line in Path(path).read_text(encoding="utf-8").splitlines() if line.strip()]


def latest_scripted(records: list[dict]) -> dict | None:
    """The newest run on the scripted gateway that has every golden case: the full deterministic run."""
    for record in reversed(records):
        if record.get("model_id") == SCRIPTED_MODEL and cases_in(record) == set(CASES):
            return record
    return None


def latest_live(records: list[dict]) -> dict | None:
    """The newest run made with a real model (any model id other than the scripted one) that has every case."""
    for record in reversed(records):
        if record.get("model_id") != SCRIPTED_MODEL and cases_in(record) == set(CASES):
            return record
    return None


def cases_in(record: dict) -> set[str]:
    return {result["metric_id"].split("-", 1)[0] for result in record.get("results", [])}


def _number(value) -> str:
    if isinstance(value, float):
        return f"{value:.4f}".rstrip("0").rstrip(".") if value != int(value) else str(int(value))
    return str(value)


def _cell(record: dict, labelled: list[tuple[str, str]]) -> tuple[str, str]:
    by_id = {r["metric_id"]: r for r in record["results"]}
    parts, targets = [], []
    for label, metric_id in labelled:
        metric = by_id[metric_id]
        parts.append(f"{label} {_number(metric['measured'])}")
        targets.append(f"{_SYMBOL.get(metric['comparator'], metric['comparator'])} {_number(metric['target'])}")
    return ", ".join(parts), " / ".join(targets)


def _passing(record: dict, case: str) -> tuple[int, int]:
    mine = [r for r in record["results"] if r["metric_id"].split("-", 1)[0] == case]
    return sum(1 for r in mine if r["passed"]), len(mine)


def _table(record: dict, only: tuple[str, ...] = CASES) -> list[str]:
    rows = ["| Case | What it measures | Headline | Target | Metrics passing |", "|---|---|---|---|---|"]
    for case in only:
        name, what, labelled = HEADLINES[case]
        headline, target = _cell(record, labelled)
        ok, total = _passing(record, case)
        rows.append(f"| **{case}** {name} | {what} | {headline} | {target} | {ok} of {total} |")
    return rows


def _prompts(record: dict) -> str:
    return ", ".join(f"`{name}` {version}" for name, version in sorted(record["prompt_versions"].items()))


def _run_line(record: dict) -> str:
    return f"run {record['run_at'][:19].replace('T', ' ')} UTC, code revision `{record['revision']}`, model id `{record['model_id']}`"


def _failures(record: dict) -> list[str]:
    """The metrics that failed in a run, said in words with the first problem the harness found: a failing real-model run is stated, not left to a table cell."""
    out: list[str] = []
    for r in record["results"]:
        if r["passed"]:
            continue
        first = re.search(r"first problem: ([^)]*)", r.get("detail") or "")
        sign = "at most" if r["comparator"] == "at_most" else "at least"
        out.append(f"- **{r['metric_id']} failed**: measured {r['measured']}, target {sign} {r['target']}." + (f" The first problem found: {first.group(1).strip()}." if first else ""))
    return ["Failing in that run, and recorded as it came out:", "", *out, ""] if out else []


def render(records: list[dict]) -> str:
    scripted = latest_scripted(records)
    if scripted is None:
        raise ValueError("eval/results.jsonl has no full run (all nine golden cases) on the scripted gateway")
    metrics = len(scripted["results"])
    passed = sum(1 for r in scripted["results"] if r["passed"])
    lines = [
        BEGIN, "",
        "### Headline numbers: all nine golden cases", "",
        (f"The default run drives the brief through a scripted gateway, so these numbers measure P2's grounding, approval and delta machinery, not a language model: "
         f"the record's model id says so (`{scripted['model_id']}`) rather than naming a model that was never called. Recorded in `eval/results.jsonl`: {_run_line(scripted)}."), "",
        *_table(scripted), "",
        f"**{passed} of {metrics} metrics pass** across the nine cases. Prompts used: {_prompts(scripted)}.", "",
    ]
    live = latest_live(records)
    if live is not None:
        lines += [
            "#### The same harness on a real model", "",
            (f"GC1 and GC2 are the two cases a language model can move: with `{live['model_id']}` the brief is written by the model itself, so GC1 is its own first-attempt "
             f"citation rate and GC2 probes what it actually wrote. Recorded: {_run_line(live)}."), "",
            *_table(live, ("GC1", "GC2")), "",
            f"{sum(1 for r in live['results'] if r['passed'])} of {len(live['results'])} metrics pass in that run. Prompts used: {_prompts(live)}.", "",
            *_failures(live),
        ]
    lines += ["Reproduce: `uv run python scripts/run_eval.py` (and `--live-bedrock` for the real-model run); every run appends a record to `eval/results.jsonl`.", "", END]
    return "\n".join(lines)


def block_of(readme: str) -> str | None:
    if BEGIN not in readme or END not in readme:
        return None
    return readme[readme.index(BEGIN): readme.index(END) + len(END)]


def update_readme(readme: str, records: list[dict]) -> str:
    """The README with the headline block (re)written from the records: replaced between the markers, or added before "## Getting started"."""
    block = render(records)
    existing = block_of(readme)
    if existing is not None:
        return readme.replace(existing, block, 1)
    anchor = "## Getting started"
    if anchor in readme:
        return readme.replace(anchor, "## Evaluation\n\n" + block + "\n\n" + anchor, 1)
    return readme.rstrip("\n") + "\n\n## Evaluation\n\n" + block + "\n"


def readme_matches(readme: str, records: list[dict]) -> bool:
    return block_of(readme) == render(records)
