#!/usr/bin/env python3
"""P2's eval entry point.

Prints PM-07's golden case 3 report (precision/recall of the diff engine
against hand labels), then runs every case registered with spine's eval
harness (PM-12: GC1 citation rate, GC2 fabricated-claim count), printing
one line per metric and appending the run to eval/results.jsonl, tagged
with a model id and every prompt capability's current version.

The default run drives the brief through a scripted gateway, so its
model id is "scripted-gateway": the numbers measure P2's grounding
machinery, not a language model, and the results file says so rather than
naming a model that was never called. Pass --model-id to tag a run made
with a different gateway deliberately.

With --live-bedrock the brief is generated by Claude on Bedrock (the model set in .env), recorded under a model id like
"bedrock:global.anthropic.claude-sonnet-4-6": GC1 then measures Claude's own first-attempt citation rate and GC2 probes the brief it actually wrote.
Only the model's own settings are read from .env (by name, never printed); nothing else in it, such as the real Teams publisher, is loaded.

With --live-ollama MODEL the brief is generated by that real local model
instead: GC1 then measures the model's own first-attempt citation rate and GC2
probes the brief it actually wrote. One model pass feeds both, and it is slow
(about 15 minutes for gemma2:9b on a laptop).

Every record also names the code revision it ran on and whether the working
tree had uncommitted changes, so a recorded number can be tied to its code.

Usage:
    uv run python scripts/run_eval.py
    uv run python scripts/run_eval.py --live-bedrock
    uv run python scripts/run_eval.py --live-ollama gemma2:9b
"""

from __future__ import annotations

import argparse
import os
import subprocess
import sys
import tempfile
from pathlib import Path

# Same fix scripts/seed.py already applies, for the same reason (see that
# script's own comment, and P3_Agents/DECISION_LOG.md's CHN-33 entry):
# uv's editable-install .pth redirect for path dependencies (spine, p1) is
# unreliable outside a handful of execution contexts, and pytest's
# `pythonpath` ini option only takes effect inside pytest's own import
# machinery -- a bare script run via `uv run python scripts/run_eval.py`
# needs the exact same three paths inserted here directly.
_REPO_ROOT = Path(__file__).resolve().parent.parent
_P1_REPO_ROOT = _REPO_ROOT.parent / "P3_Agents"
for _path in (_REPO_ROOT / "src", _P1_REPO_ROOT / "src", _REPO_ROOT / "packages" / "spine" / "src"):
    sys.path.insert(0, str(_path))

from spine.eval.cases import GoldenCaseRegistry
from spine.eval.runner import run_eval
from spine.prompts.registry import PromptRegistry

from pm.eval.pm18_cases import report as gc4_report
from pm.eval.pm20_cases import report as gc5_report
from pm.eval.pm23_cases import report as gc9_report
from pm.eval.pm25_cases import report as gc7_report
from pm.eval.pm27_cases import report as gc8_report
from pm.eval.registrations import register_all
from pm.eval.runner import main as print_golden_case_3
from pm.prompts import format_prompts, prompt_record

RESULTS_PATH = _REPO_ROOT / "eval" / "results.jsonl"
DEFAULT_MODEL_ID = "scripted-gateway"


MODEL_ENV_NAMES = ("LLM_PROVIDER", "AWS_REGION", "AWS_DEFAULT_REGION", "BEDROCK_MODEL_ID", "AWS_ACCESS_KEY_ID", "AWS_SECRET_ACCESS_KEY", "AWS_SESSION_TOKEN", "AWS_PROFILE")


def isolate_from_the_outside_world() -> None:
    """An eval run never posts to Teams, never touches the Supabase mirror and never rewrites the risk log, whatever the environment holds. The cases pass their
    own spy publishers and policies; this makes sure that nothing that reaches for the real ones can find them."""
    os.environ.update({"TEAMS_PUBLISHER_MODE": "mock", "POWER_AUTOMATE_FLOW_URL": "", "PM_SUPABASE_MIRROR": "0", "SUPABASE_DB_URL": "",
                       "PM_RISK_LOG_SYNC": "0", "PM_AUTO_APPROVE": "0", "PM_CHANNEL_BRIEFS": "", "PM_WEEKLY_REPORT": "", "PM_COMMITMENT_FOLLOWUP": "0"})


def load_model_settings(env_path: Path) -> None:
    """Read ONLY the model's own settings from .env, by name, into this process. The rest of the file (the real Teams flow, the mirror, the approvers) is not loaded."""
    from dotenv import dotenv_values

    for name, value in dotenv_values(env_path).items():
        if name in MODEL_ENV_NAMES and value and name not in os.environ:
            os.environ[name] = value


def bedrock_model_label() -> str:
    """"bedrock:" and the model's own name: the last part of BEDROCK_MODEL_ID, never the account-specific ARN in front of it."""
    raw = (os.environ.get("BEDROCK_MODEL_ID") or "").strip()
    if not raw:
        raise SystemExit("BEDROCK_MODEL_ID is not set (in .env or the environment): there is no model to evaluate")
    return "bedrock:" + raw.rsplit("/", 1)[-1]


def code_revision() -> dict:
    """The git revision this run is on, and whether tracked files differ from
    it (the results file itself does not count: every run changes it)."""
    def git(*args: str) -> str | None:
        done = subprocess.run(["git", *args], cwd=_REPO_ROOT, capture_output=True, text=True, check=False)
        return done.stdout.strip() if done.returncode == 0 else None

    status = git("status", "--porcelain", "--", ".", ":!eval/results.jsonl")
    return {"revision": git("rev-parse", "--short", "HEAD"), "dirty": bool(status)}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--model-id", default=None)
    live = parser.add_mutually_exclusive_group()
    live.add_argument("--live-ollama", metavar="MODEL", help="evaluate a real local model, e.g. gemma2:9b")
    live.add_argument("--live-bedrock", action="store_true", help="evaluate Claude on Bedrock, the model set by BEDROCK_MODEL_ID in .env")
    args = parser.parse_args()
    isolate_from_the_outside_world()
    if args.live_bedrock:
        load_model_settings(_REPO_ROOT / ".env")
        os.environ["LLM_PROVIDER"] = "bedrock"
    model_id = args.model_id or (f"ollama:{args.live_ollama}" if args.live_ollama else bedrock_model_label() if args.live_bedrock else DEFAULT_MODEL_ID)

    prompts = PromptRegistry(_REPO_ROOT / "prompts")
    print(format_prompts(prompts))
    print()
    print_golden_case_3()
    print()
    print(gc4_report())
    print()
    print(gc5_report())
    print()
    print(gc9_report())
    print()
    print(gc7_report())
    print()
    print(gc8_report())
    print()

    registry = GoldenCaseRegistry()
    if args.live_ollama:
        from spine.llm.gateway import LLMGateway

        work = Path(tempfile.mkdtemp(prefix="pm_eval_live_"))
        register_all(
            registry,
            live=True,
            gateway_factory=lambda: LLMGateway(
                provider="ollama", ollama_model=args.live_ollama,
                cache_dir=work / "cache", call_log_path=work / "calls.jsonl",
            ),
        )
    elif args.live_bedrock:
        from spine.llm.gateway import LLMGateway

        work = Path(tempfile.mkdtemp(prefix="pm_eval_live_"))
        register_all(
            registry,
            live=True,
            gateway_factory=lambda: LLMGateway(provider="bedrock", cache_dir=work / "cache", call_log_path=work / "calls.jsonl"),
        )
    else:
        register_all(registry)
    summary = run_eval(
        registry,
        model_id=model_id,
        prompt_versions={name: prompts.get(name).version for name in prompts.list_capabilities()},
        results_path=RESULTS_PATH,
        extra={**code_revision(), **prompt_record(prompts)},
        out=sys.stdout,  # looked up now, not when the harness was imported
    )
    return 0 if summary.all_passed else 1


if __name__ == "__main__":
    raise SystemExit(main())
